"""
logsloth/reporter.py — Markdown incident report export.

Generates sanitised reports. Raw log content is never included.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

from logsloth.models import Incident


def _fmt_ts(dt: datetime | None) -> str:
    return dt.strftime("%Y-%m-%d %H:%M:%S UTC") if dt else "unknown"


def incident_to_markdown(incident: Incident) -> str:
    """Render a single incident as a Markdown string."""
    lines: list[str] = []

    lines.append(f"# Incident Report: {incident.title}")
    lines.append("")
    lines.append(f"**Fingerprint:** `{incident.fingerprint}`")
    lines.append(f"**Severity:** {incident.severity.value}")
    lines.append(f"**Occurrences:** {incident.occurrence_count}")
    lines.append(f"**First seen:** {_fmt_ts(incident.first_seen)}")
    lines.append(f"**Last seen:** {_fmt_ts(incident.last_seen)}")
    if incident.spike_flagged:
        lines.append(f"**⚠ Spike detected:** {incident.spike_reason}")
    lines.append(f"**Sources:** {', '.join(incident.source_files) or 'unknown'}")
    lines.append("")

    lines.append("## Representative Message (Sanitised)")
    lines.append("```")
    lines.append(incident.representative_message)
    lines.append("```")
    lines.append("")

    if incident.representative_stack:
        lines.append("## Stack Trace (Sanitised)")
        lines.append("```")
        lines.append(incident.representative_stack)
        lines.append("```")
        lines.append("")

    if incident.ai_analyzed:
        lines.append("## AI Diagnostic Summary")
        lines.append("")
        if incident.ai_title:
            lines.append(f"**{incident.ai_title}**")
            lines.append("")
        lines.append(incident.ai_summary)
        lines.append("")

        if incident.ai_probable_causes:
            lines.append("### Probable Causes")
            for cause in incident.ai_probable_causes:
                lines.append(f"- {cause}")
            lines.append("")

        if incident.ai_evidence:
            lines.append("### Supporting Evidence")
            for ev in incident.ai_evidence:
                lines.append(f"- {ev}")
            lines.append("")

        if incident.ai_suggested_checks:
            lines.append("### Suggested Investigation Steps")
            for step in incident.ai_suggested_checks:
                lines.append(f"- {step}")
            lines.append("")

        lines.append(f"**Confidence:** {incident.ai_confidence or 'unspecified'}")
        if incident.ai_limitations:
            lines.append(f"**Limitations:** {incident.ai_limitations}")
        lines.append("")
    else:
        lines.append("## AI Analysis")
        lines.append("_AI analysis not yet performed or unavailable._")
        if incident.ai_error:
            lines.append(f"> Error: {incident.ai_error}")
        lines.append("")

    lines.append("---")
    lines.append(f"_Report generated by LogSloth at {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}_")

    return "\n".join(lines)


def export_report(incident: Incident, reports_dir: Path) -> Path:
    """Write a Markdown report for *incident* to *reports_dir*."""
    reports_dir.mkdir(parents=True, exist_ok=True)
    safe_title = "".join(c if c.isalnum() or c in "-_" else "_" for c in incident.title[:40])
    filename = f"{incident.fingerprint}_{safe_title}.md"
    path = reports_dir / filename
    path.write_text(incident_to_markdown(incident), encoding="utf-8")
    return path


def export_all_reports(incidents: dict[str, Incident], reports_dir: Path) -> list[Path]:
    """Export Markdown reports for all incidents."""
    return [export_report(inc, reports_dir) for inc in incidents.values()]
